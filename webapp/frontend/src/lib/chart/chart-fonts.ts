/** True single-glyph ink, independent of WebKit's clamped Canvas metrics. */
export function bundledGlyphInkBounds(
  text: string, font: string, size: number,
  weight: string | number = 400, style = "normal",
): Readonly<{ x: number; y: number; w: number; h: number }> | undefined {
  if (style !== "normal" || Array.from(text).length !== 1) return;
  const family = font.split(",", 1)[0].trim().replace(/^(['"])(.*)\1$/, "$2");
  const numericWeight = weight === "normal" ? 400 : weight === "bold" ? 700 : Number(weight);
  const ink = BUNDLED_GLYPH_INK[`${family}/${numericWeight}`]?.[text];
  if (!ink) return;
  const px = Math.max(1, Math.round(size));
  return { x: ink[0] * px, y: ink[1] * px, w: ink[2] * px, h: ink[3] * px };
}
